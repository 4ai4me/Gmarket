import type { CropCategory, CropProfile, CultivationMethodProfile } from '../types/garak';

interface CompactCropSpec {
  id: string;
  name: string;
  aliases: string[];
  category: CropCategory;
  variety: string;
  unitLabel: string;
  unitKg: number;
  unitDesc: string;
  monthly: [
    number, number, number, number, number, number,
    number, number, number, number, number, number
  ];
  vol: number;
  sow: number[];
  harvest: number[];
  peak: number[];
  diff: '초급' | '중급' | '고급';
  soil: string;
  risk: string;
  methods: CultivationMethodProfile[];
}

function makeProfile(s: CompactCropSpec): CropProfile {
  return {
    id: s.id,
    name: s.name,
    aliases: s.aliases,
    category: s.category,
    representativeVariety: s.variety,
    standardUnitLabel: s.unitLabel,
    standardUnitKg: s.unitKg,
    nativeUnitType: s.unitLabel,
    nativeUnitDescription: s.unitDesc,
    monthlyPricePerKg: s.monthly,
    weeklyVolatility: s.vol,
    sowingMonths: s.sow,
    harvestMonths: s.harvest,
    peakPriceMonths: s.peak,
    difficulty: s.diff,
    soilAndClimateNote: s.soil,
    keyRiskNote: s.risk,
    methods: s.methods,
    dataSourceTier: 'curated',
  };
}

